#!/usr/bin/env python3
"""Build tool to generate GV2BuildIdentity.gen.h containing build-time source revision and diff hash."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from Tools.Testing.ue_test_report import (
    compute_source_diff_hash,
    compute_source_revision,
)


def generate_header(repo_root: Path, output_path: Path) -> int:
    source_revision = compute_source_revision(repo_root)
    source_diff_hash = compute_source_diff_hash(repo_root)

    content = f"""// Automatically generated by Tools/Build/generate_build_identity.py. Do not edit manually.
#pragma once

#define GV2_BUILD_SOURCE_REVISION "{source_revision}"
#define GV2_BUILD_SOURCE_DIFF_HASH "{source_diff_hash}"
"""

    output_path.parent.mkdir(parents=True, exist_ok=True)
    if output_path.is_file():
        existing = output_path.read_text(encoding="utf-8")
        if existing == content:
            # Header is already up to date; avoid touching mtime to prevent unnecessary rebuilds
            print(f"[generate_build_identity] Up to date: {output_path} (rev: {source_revision[:8]}, diff: {source_diff_hash[:8]})")
            return 0

    output_path.write_text(content, encoding="utf-8")
    print(f"[generate_build_identity] Generated: {output_path} (rev: {source_revision[:8]}, diff: {source_diff_hash[:8]})")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate GV2BuildIdentity.gen.h")
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=REPO_ROOT,
        help="Path to repository root",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=REPO_ROOT / "Source" / "GV2" / "Public" / "GV2BuildIdentity.gen.h",
        help="Path to output header file",
    )
    args = parser.parse_args()
    return generate_header(args.repo_root.resolve(), args.output.resolve())


if __name__ == "__main__":
    sys.exit(main())
